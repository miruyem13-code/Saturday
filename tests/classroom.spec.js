import { test, expect } from '@playwright/test'
import { jobs } from '../src/data.js'

test('all nine offers contain assignment details and working application buttons', async ({ page }) => {
 const errors = []; page.on('pageerror', e => errors.push(e.message))
 await page.goto('/')
 await expect(page.locator('.job-card')).toHaveCount(9)
 await expect(page.locator('.job-grid')).toHaveCSS('grid-template-columns', /\S+ \S+ \S+/)
 for (const job of jobs) {
  const card = page.locator('.job-card').filter({has: page.getByRole('heading', {name: job.title, exact:true})})
  await expect(card).toContainText(`${job.start}–${job.end}`)
  await expect(card).toContainText(`${job.hours} hours`)
  await card.getByRole('button', {name:'View Details'}).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText(`Saturday ${job.shift.toLowerCase()}`)
  await expect(dialog).toContainText(job.requirement)
  for (const duty of job.duties) await expect(dialog).toContainText(duty)
  await dialog.getByRole('button', {name:'Close dialog'}).click()
  await card.getByRole('button', {name:'Apply Now'}).click()
  await expect(page.getByRole('dialog')).toContainText(job.title)
  await page.getByRole('button', {name:'Cancel', exact:true}).click()
 }
 expect(errors).toEqual([])
 await page.evaluate(() => window.scrollTo(0,0))
 await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true})
})

